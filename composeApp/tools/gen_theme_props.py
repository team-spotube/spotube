#!/usr/bin/env python3
"""Generates GeneratedThemeProps.kt (JSON theme engine) from the Millennium *sources* jar.

usage: gen_theme_props.py <extracted-millennium-sources-dir> <output.kt>
Re-run after bumping `millennium` in gradle/libs.versions.toml.
"""
import re, sys, glob, os

src, out = sys.argv[1], sys.argv[2]
LICENSE = open(os.path.join(os.path.dirname(__file__), "..", "src/commonMain/kotlin/org/spotube/spotube/core/ui/theming/AppTheme.kt")).read().split("*/")[0] + "*/\n"

props = {}      # class -> [(field, type)]
themes = {}     # class -> [(field, kind, propsClass)]
for f in glob.glob(src + "/commonMain/org/spotube/millennium/composables/*.kt"):
    s = open(f).read()
    for m in re.finditer(r'data class (Millennium\w+Properties)\(\n(.*?)\n\)', s, re.S):
        fields = []
        for line in m.group(2).split("\n"):
            mm = re.match(r'\s*(?:override\s+)?val (\w+): ([^=]+?)(?: = .*)?,?$', line)
            if mm:
                fields.append((mm.group(1), mm.group(2).strip().rstrip(",").replace("androidx.compose.ui.graphics.", "")))
        props[m.group(1)] = fields
    for m in re.finditer(r'data class (Millennium\w+Theme)\(([^)]*)\)', s, re.S):
        slots = []
        for mm in re.finditer(r'val (\w+): (?:MillenniumControlStateProperty<(\w+)>|(\w+Properties))', m.group(2)):
            slots.append((mm.group(1), "states" if mm.group(2) else "single", mm.group(2) or mm.group(3)))
        themes[m.group(1)] = slots

comp = open(src + "/commonMain/org/spotube/millennium/theme/Theme.kt").read()
comp_fields = re.findall(r'val (\w+Theme): (Millennium\w+Theme)\b', comp.split("data class MillenniumThemeComponents(")[1].split("\n)")[0])

READ = {
    "Dp": "r.dp(\"{n}\", p.{n})", "Color?": "r.color(\"{n}\", p.{n})", "Brush?": "r.brush(\"{n}\", p.{n})",
    "PaddingValues": "r.padding(\"{n}\", p.{n})", "Float": "r.float(\"{n}\", p.{n})", "TextStyle": "r.textStyle(\"{n}\", p.{n})",
    "Shape": "r.shape(\"{n}\", p.{n})", "Int": "r.int(\"{n}\", p.{n})", "DpSize": "r.dpSize(\"{n}\", p.{n})",
    "Boolean": "r.bool(\"{n}\", p.{n})", "Long": "r.long(\"{n}\", p.{n})", "List<Color>?": "r.colors(\"{n}\", p.{n})",
    "MillenniumButtonMotion": "r.motion(\"{n}\", p.{n})",
    "Int?": "r.intOrNull(\"{n}\", p.{n})", "Float?": "r.floatOrNull(\"{n}\", p.{n})", "Dp?": "r.dpOrNull(\"{n}\", p.{n})",
    "Shape?": "r.shapeOrNull(\"{n}\", p.{n})", "TextStyle?": "r.textStyleOrNull(\"{n}\", p.{n})",
    "MillenniumButtonStyle": "r.buttonStyle(\"{n}\", p.{n})",
}
o = [LICENSE, "\n// GENERATED by composeApp/tools/gen_theme_props.py from the Millennium sources. Do not edit.\n\n",
     "package org.spotube.spotube.core.ui.theming.engine\n\n",
     "import org.spotube.millennium.composables.*\nimport org.spotube.millennium.theme.*\n\n"]
for cls, fields in sorted(props.items()):
    o.append(f"internal fun apply{cls.removeprefix('Millennium')}(p: {cls}, r: PropReader): {cls} = p.copy(\n")
    for n, t in fields:
        if t not in READ:
            sys.exit(f"unsupported type {t} in {cls}.{n}")
        o.append(f"    {n} = " + READ[t].format(n=n) + ",\n")
    o.append(")\n\n")
o.append("/** Applies the theme's `components.*` onto every Millennium component theme. */\n")
o.append("internal fun ThemeCompiler.compileAllComponents(c: MillenniumThemeComponents): MillenniumThemeComponents = c.copy(\n")
for fld, cls in comp_fields:
    key = fld.removesuffix("Theme")
    slots = themes[cls]
    multi = len(slots) > 1
    args = []
    for name, kind, pc in slots:
        variant = ('"' + ("main" if name == "states" else name) + '"') if multi else "null"
        ap = "apply" + pc.removeprefix("Millennium")
        if kind == "states":
            args.append(f'{name} = stateProp("{key}", c.{fld}.{name}, ::{ap}, {variant})')
        else:
            args.append(f'{name} = singleProp("{key}", c.{fld}.{name}, ::{ap}, {variant})')
    o.append(f"    {fld} = c.{fld}.copy(\n        " + ",\n        ".join(args) + "\n    ),\n")
o.append(")\n")
open(out, "w").write("".join(o))
print("components:", len(comp_fields), "props classes:", len(props))
