#!/usr/bin/env node
// Generates GeneratedThemeProps.kt (the JSON theme engine's mapping onto Millennium) from the library's *sources* jar.
//
// usage: node composeApp/tools/gen-theme-props.mjs <extracted-millennium-sources-dir> <output.kt>
//
// Extract the jar first:  unzip -q ~/.m2/repository/org/spotube/millennium/millennium-jvm/<version>/millennium-jvm-<version>-sources.jar -d /tmp/millennium-src
// Re-run after bumping `millennium` in gradle/libs.versions.toml. It fails on property types it has no reader for:
// add the reader to PropReader (ThemeCompiler.kt) and to READ below.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [src, out] = process.argv.slice(2);
if (!src || !out) {
  console.error('usage: gen-theme-props.mjs <extracted-millennium-sources-dir> <output.kt>');
  process.exit(2);
}

const HERE = dirname(fileURLToPath(import.meta.url));
const appTheme = readFileSync(join(HERE, '..', 'src/commonMain/kotlin/org/spotube/spotube/core/ui/theming/AppTheme.kt'), 'utf8');
const LICENSE = `${appTheme.split('*/')[0]}*/\n`;

/** class -> [[field, type]] */
const props = new Map();
/** class -> [[field, kind, propsClass]] */
const themes = new Map();

const composables = join(src, 'commonMain/org/spotube/millennium/composables');
for (const file of readdirSync(composables).filter((f) => f.endsWith('.kt'))) {
  const text = readFileSync(join(composables, file), 'utf8');
  for (const m of text.matchAll(/data class (Millennium\w+Properties)\(\n(.*?)\n\)/gs)) {
    const fields = [];
    for (const line of m[2].split('\n')) {
      const mm = line.match(/^\s*(?:override\s+)?val (\w+): ([^=]+?)(?: = .*)?,?$/);
      if (mm) fields.push([mm[1], mm[2].trim().replace(/,+$/, '').replace('androidx.compose.ui.graphics.', '')]);
    }
    props.set(m[1], fields);
  }
  for (const m of text.matchAll(/data class (Millennium\w+Theme)\(([^)]*)\)/gs)) {
    const slots = [];
    for (const mm of m[2].matchAll(/val (\w+): (?:MillenniumControlStateProperty<(\w+)>|(\w+Properties))/g)) {
      slots.push([mm[1], mm[2] ? 'states' : 'single', mm[2] ?? mm[3]]);
    }
    themes.set(m[1], slots);
  }
}

const themeKt = readFileSync(join(src, 'commonMain/org/spotube/millennium/theme/Theme.kt'), 'utf8');
const componentsBody = themeKt.split('data class MillenniumThemeComponents(')[1].split('\n)')[0];
const compFields = [...componentsBody.matchAll(/val (\w+Theme): (Millennium\w+Theme)\b/g)].map((m) => [m[1], m[2]]);

/** Kotlin property type -> the PropReader call that reads it from the theme JSON ({n} = the property name). */
const READ = {
  Dp: 'r.dp("{n}", p.{n})', 'Color?': 'r.color("{n}", p.{n})', 'Brush?': 'r.brush("{n}", p.{n})',
  PaddingValues: 'r.padding("{n}", p.{n})', Float: 'r.float("{n}", p.{n})', TextStyle: 'r.textStyle("{n}", p.{n})',
  Shape: 'r.shape("{n}", p.{n})', Int: 'r.int("{n}", p.{n})', DpSize: 'r.dpSize("{n}", p.{n})',
  Boolean: 'r.bool("{n}", p.{n})', Long: 'r.long("{n}", p.{n})', 'List<Color>?': 'r.colors("{n}", p.{n})',
  MillenniumButtonMotion: 'r.motion("{n}", p.{n})',
  'Int?': 'r.intOrNull("{n}", p.{n})', 'Float?': 'r.floatOrNull("{n}", p.{n})', 'Dp?': 'r.dpOrNull("{n}", p.{n})',
  'Shape?': 'r.shapeOrNull("{n}", p.{n})', 'TextStyle?': 'r.textStyleOrNull("{n}", p.{n})',
  MillenniumButtonStyle: 'r.buttonStyle("{n}", p.{n})',
};

const strip = (s, prefix) => (s.startsWith(prefix) ? s.slice(prefix.length) : s);
const unsuffix = (s, suffix) => (s.endsWith(suffix) ? s.slice(0, -suffix.length) : s);

let o = LICENSE;
o += '\n// GENERATED by composeApp/tools/gen-theme-props.mjs from the Millennium sources. Do not edit.\n\n';
o += 'package org.spotube.spotube.core.ui.theming.engine\n\n';
o += 'import org.spotube.millennium.composables.*\nimport org.spotube.millennium.theme.*\n\n';

for (const [cls, fields] of [...props].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
  o += `internal fun apply${strip(cls, 'Millennium')}(p: ${cls}, r: PropReader): ${cls} = p.copy(\n`;
  for (const [n, t] of fields) {
    if (!(t in READ)) {
      console.error(`unsupported type ${t} in ${cls}.${n}`);
      process.exit(1);
    }
    o += `    ${n} = ${READ[t].replaceAll('{n}', n)},\n`;
  }
  o += ')\n\n';
}

o += "/** Applies the theme's `components.*` onto every Millennium component theme. */\n";
o += 'internal fun ThemeCompiler.compileAllComponents(c: MillenniumThemeComponents): MillenniumThemeComponents = c.copy(\n';
for (const [fld, cls] of compFields) {
  const key = unsuffix(fld, 'Theme');
  const slots = themes.get(cls);
  const multi = slots.length > 1;
  const args = slots.map(([name, kind, pc]) => {
    const variant = multi ? `"${name === 'states' ? 'main' : name}"` : 'null';
    const apply = `apply${strip(pc, 'Millennium')}`;
    const call = kind === 'states' ? 'stateProp' : 'singleProp';
    return `${name} = ${call}("${key}", c.${fld}.${name}, ::${apply}, ${variant})`;
  });
  o += `    ${fld} = c.${fld}.copy(\n        ${args.join(',\n        ')}\n    ),\n`;
}
o += ')\n';

writeFileSync(out, o);
console.log(`components: ${compFields.length} props classes: ${props.size}`);
